/**
 * Generates, from INSEE's official geographic code (Etalab open licence):
 * - js/data/communes.js: current, delegated and associated communes, by department;
 * - js/data/commune-changes.js (with the events file): former communes and the commune that
 *   holds their civil registers today (merges, new communes, renamings since 1943).
 *
 *   node scripts/build-communes.mjs v_commune_<year>.csv [v_mvt_commune_<year>.csv]
 *
 * Source: https://www.insee.fr/fr/information/2560452
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , source, events] = process.argv;
if (!source) {
  console.error('Usage: node scripts/build-communes.mjs v_commune_<year>.csv [v_mvt_commune_<year>.csv]');
  process.exit(1);
}

/** CSV file -> rows as objects, by column name. */
function readCsv(file) {
  const rows = readFileSync(file, 'utf8').trim().split(/\r?\n/).map((line) => line.split(',').map((x) => x.replace(/^"|"$/g, '')));
  const head = rows.shift();
  return rows.map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

// A commune's department: its first two characters, three for overseas (971…)
const deptOf = (code) => (code.startsWith('97') ? code.slice(0, 3) : code.slice(0, 2));

/** Writes a data file: { dept: 'a|b|…' }, departments in order. */
function writeData(file, comment, name, byDept) {
  const depts = [...byDept.keys()].sort();
  const body = depts.map((d) => `  '${d}': ${JSON.stringify([...byDept.get(d)].sort().join('|'))},`).join('\n');
  writeFileSync(new URL('../js/data/' + file, import.meta.url), `/**\n${comment}\n */\nexport const ${name} = {\n${body}\n};\n`);
}

const communes = readCsv(source);
const byDept = new Map();
for (const r of communes) {
  if (!['COM', 'COMD', 'COMA'].includes(r.TYPECOM)) continue;
  const dept = deptOf(r.COM);
  if (!byDept.has(dept)) byDept.set(dept, new Set());
  byDept.get(dept).add(r.LIBELLE);
}
writeData('communes.js', ` * French communes (current, delegated and associated) by department, separated by "|".
 * Generated by scripts/build-communes.mjs from INSEE's official geographic code: do not edit by hand.`, 'COMMUNES', byDept);
console.log(`communes.js: ${byDept.size} departments, ${[...byDept.values()].reduce((n, s) => n + s.size, 0)} communes`);

if (events) {
  // Current communes, and the commune a delegated or associated commune belongs to
  const now = new Map(communes.filter((r) => r.TYPECOM === 'COM').map((r) => [r.COM, r.LIBELLE]));
  const parent = new Map(communes.filter((r) => r.COMPARENT && r.TYPECOM !== 'COM').map((r) => [r.COM, r.COMPARENT]));
  const changes = readCsv(events).sort((a, b) => a.DATE_EFF.localeCompare(b.DATE_EFF));

  /** Code of the current commune that took over commune `code`, or null (commune gone). */
  const current = (code, seen = new Set()) => {
    if (now.has(code)) return code;
    if (parent.has(code)) return parent.get(code);
    if (seen.has(code)) return null;
    seen.add(code);
    const next = changes.filter((e) => e.COM_AV === code && e.TYPECOM_AP === 'COM' && e.COM_AP !== code).pop();
    return next ? current(next.COM_AP, seen) : null;
  };

  // Every name a commune has had, with its code; a delegated or associated commune counts too
  const named = [
    ...communes.filter((r) => r.TYPECOM === 'COMD' || r.TYPECOM === 'COMA').map((r) => [r.COM, r.LIBELLE]),
    ...changes.flatMap((e) => [[e.COM_AV, e.LIBELLE_AV, e.TYPECOM_AV], [e.COM_AP, e.LIBELLE_AP, e.TYPECOM_AP]])
      .filter(([, , type]) => ['COM', 'COMD', 'COMA'].includes(type)),
  ];
  const livingNames = new Set(communes.filter((r) => r.TYPECOM === 'COM').map((r) => deptOf(r.COM) + '|' + r.LIBELLE));
  const target = new Map(); // "dept|old name" -> current name, or null when ambiguous
  for (const [code, name] of named) {
    const cur = current(code);
    const dept = deptOf(code);
    const k = dept + '|' + name;
    if (!cur || now.get(cur) === name || livingNames.has(k)) continue;
    const to = now.get(cur) + (deptOf(cur) === dept ? '' : ` (${deptOf(cur)})`);
    target.set(k, target.has(k) && target.get(k) !== to ? null : to);
  }
  const moved = new Map();
  for (const [k, to] of target) {
    if (!to) continue;
    const [dept, name] = k.split('|');
    if (!moved.has(dept)) moved.set(dept, new Set());
    moved.get(dept).add(`${name}>${to}`);
  }
  writeData('commune-changes.js', ` * Former French communes and the commune that holds their civil registers today, by department:
 * "former name>current name", separated by "|"; the current department follows in brackets when it changed.
 * Generated by scripts/build-communes.mjs from INSEE's official geographic code: do not edit by hand.`, 'COMMUNE_CHANGES', moved);
  console.log(`commune-changes.js: ${[...moved.values()].reduce((n, s) => n + s.size, 0)} former communes`);
}
